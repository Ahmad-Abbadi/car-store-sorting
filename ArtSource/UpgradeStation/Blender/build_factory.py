def tag(obj,name,mat):
    obj.name=name;obj.data.materials.clear();obj.data.materials.append(mat)
    groups.setdefault(current,[]).append(obj)
    return obj

def bevel(obj,r=.015,segments=3):
    mod=obj.modifiers.new('Soft manufactured edges','BEVEL');mod.width=r;mod.segments=segments
    bpy.context.view_layer.objects.active=obj;bpy.ops.object.modifier_apply(modifier=mod.name)
    for p in obj.data.polygons:p.use_smooth=True
    mod=obj.modifiers.new('Weighted corner normals','WEIGHTED_NORMAL');mod.keep_sharp=True;mod.weight=50
    bpy.ops.object.modifier_apply(modifier=mod.name)
    return obj

def box(name,p,s,mat,r=.012,rot=None):
    bpy.ops.mesh.primitive_cube_add(size=1,location=p)
    o=bpy.context.object;o.dimensions=s
    bpy.ops.object.transform_apply(location=False,rotation=False,scale=True)
    if rot:o.rotation_euler=rot
    tag(o,name,mat)
    return bevel(o,r,3)

def cyl(name,p,r,depth,mat,axis=(0,0,1),verts=32):
    bpy.ops.mesh.primitive_cylinder_add(vertices=verts,radius=r,depth=depth,location=p)
    o=bpy.context.object;o.rotation_mode='QUATERNION';o.rotation_quaternion=Vector(axis).to_track_quat('Z','Y')
    tag(o,name,mat);return bevel(o,min(.004,depth*.2),2)

def rod(name,a,b,r,mat):
    a,b=Vector(a),Vector(b)
    return cyl(name,(a+b)*.5,r,(a-b).length,mat,b-a,20)

def ring(name,p,major,minor,mat,rot=None):
    bpy.ops.mesh.primitive_torus_add(major_segments=48,minor_segments=8,location=p,major_radius=major,minor_radius=minor)
    o=tag(bpy.context.object,name,mat)
    if rot:o.rotation_euler=rot
    for f in o.data.polygons:f.use_smooth=True
    return o

def hose(name,points,r,mat):
    c=bpy.data.curves.new(name,'CURVE');c.dimensions='3D';c.resolution_u=8;c.bevel_depth=r;c.bevel_resolution=2
    sp=c.splines.new('BEZIER');sp.bezier_points.add(len(points)-1)
    for b,p in zip(sp.bezier_points,points):b.co=p;b.handle_left_type='AUTO';b.handle_right_type='AUTO'
    o=bpy.data.objects.new(name,c);scene.collection.objects.link(o)
    bpy.context.view_layer.objects.active=o;o.select_set(True);bpy.ops.object.convert(target='MESH');o=bpy.context.object
    tag(o,name,mat)
    for f in o.data.polygons:f.use_smooth=True
    return o

def profile(name,points,depth,center_y,mat,r=.015):
    # Extruded X/Z silhouette; visible front points toward -Y.
    vs=[(x,center_y+y,z) for y in [-depth/2,depth/2] for x,z in points]
    k=len(points);faces=[tuple(reversed(range(k))),tuple(range(k,2*k))]
    faces += [(i,(i+1)%k,(i+1)%k+k,i+k) for i in range(k)]
    mesh=bpy.data.meshes.new(name);mesh.from_pydata(vs,[],faces);mesh.update()
    o=bpy.data.objects.new(name,mesh);scene.collection.objects.link(o);tag(o,name,mat)
    bpy.context.view_layer.objects.active=o;o.select_set(True)
    bpy.ops.object.select_all(action='DESELECT');o.select_set(True)
    bpy.ops.object.mode_set(mode='EDIT');bpy.ops.mesh.select_all(action='SELECT');bpy.ops.mesh.normals_make_consistent(inside=False);bpy.ops.object.mode_set(mode='OBJECT')
    return bevel(o,r,3)

