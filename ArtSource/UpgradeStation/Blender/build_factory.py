def finish(name, color, metallic=0, rough=.3, texture='enamel'):
    m=bpy.data.materials.new(name); m.use_nodes=True
    n=m.node_tree.nodes; l=m.node_tree.links; p=n.get('Principled BSDF')
    p.inputs['Base Color'].default_value=(*color,1)
    p.inputs['Metallic'].default_value=metallic
    p.inputs['Roughness'].default_value=rough
    tex=n.new('ShaderNodeTexNoise'); tex.inputs['Scale'].default_value=180 if texture=='rubber' else 110
    tex.inputs['Detail'].default_value=2
    coord=n.new('ShaderNodeTexCoord')
    mapping=n.new('ShaderNodeVectorMath');mapping.operation='MULTIPLY'
    mapping.inputs[1].default_value=(2,2,70) if texture=='metal' else (1,1,1)
    l.new(coord.outputs['Generated'],mapping.inputs[0]);l.new(mapping.outputs[0],tex.inputs['Vector'])
    ramp=n.new('ShaderNodeValToRGB')
    strength=.08 if texture=='rubber' else .025
    ramp.color_ramp.elements[0].color=(*(c*(1-strength) for c in color),1)
    ramp.color_ramp.elements[1].color=(*(min(1,c*(1+strength)) for c in color),1)
    l.new(tex.outputs['Fac'],ramp.inputs[0]);l.new(ramp.outputs[0],p.inputs['Base Color'])
    bump=n.new('ShaderNodeBump');bump.inputs['Strength'].default_value=.14 if texture=='rubber' else .07
    bump.inputs['Distance'].default_value=.001 if texture=='rubber' else .00025
    l.new(tex.outputs['Fac'],bump.inputs['Height']);l.new(bump.outputs[0],p.inputs['Normal'])
    m['metallic']=metallic;m['roughness']=rough
    return m

