def bake(name,kind,colorspace='Non-Color'):
    im=bpy.data.images.new(name,width=2048,height=2048,alpha=True)
    im.colorspace_settings.name=colorspace
    for m in materials:
        n=m.node_tree.nodes.new('ShaderNodeTexImage');n.image=im;n.name='BAKE_'+name;m.node_tree.nodes.active=n
    print('BAKING',name,flush=True)
    bpy.ops.object.bake(type=kind)
    im.filepath_raw=str(EXPORT/(name+'.png'));im.file_format='PNG';im.save()
    return im

